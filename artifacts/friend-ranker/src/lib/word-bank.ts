function selectEvenly<T>(entries: T[], count: number): T[] {
  const uniqueEntries = [...new Set(entries)]
  if (uniqueEntries.length <= count) return uniqueEntries
  return Array.from({ length: count }, (_, index) => {
    const sourceIndex = Math.round(index * (uniqueEntries.length - 1) / (count - 1))
    return uniqueEntries[sourceIndex]
  })
}

